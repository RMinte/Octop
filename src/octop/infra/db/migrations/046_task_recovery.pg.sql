-- Interrupted turns retain their identity and completed server-tool receipts.
ALTER TABLE project_task_turns ADD COLUMN recovery_json TEXT NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS project_task_execution_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id TEXT NOT NULL UNIQUE,
    task_id TEXT NOT NULL REFERENCES project_tasks(task_id) ON DELETE CASCADE,
    turn_id TEXT NOT NULL REFERENCES project_task_turns(turn_id) ON DELETE CASCADE,
    tool_call_id TEXT NOT NULL,
    tool_name TEXT NOT NULL,
    arguments_digest TEXT NOT NULL,
    state TEXT NOT NULL CHECK (state IN ('dispatched', 'completed', 'unknown')),
    result_json TEXT NOT NULL DEFAULT '',
    worker_id TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    UNIQUE(turn_id, tool_call_id)
);
CREATE INDEX IF NOT EXISTS idx_project_task_execution_receipts_task
    ON project_task_execution_receipts(task_id);

