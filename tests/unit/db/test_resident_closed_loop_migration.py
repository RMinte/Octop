"""Upgrade already accepted resident turns without replacing their identities."""

from __future__ import annotations

import re
import shutil

import pytest

from octop.infra.db import migrate
from octop.infra.db.pool import SqlitePool


@pytest.mark.parametrize("watermark", [51, 52])
def test_resident_upgrade_and_watermark_repair_preserve_accepted_work(
    tmp_path, monkeypatch, watermark
):
    old = tmp_path / "migrations"
    old.mkdir()
    for version, source in migrate._discover("sqlite"):
        if version <= 51:
            shutil.copy2(source, old / source.name)
    pool = SqlitePool(tmp_path / "upgrade.db")
    try:
        with monkeypatch.context() as patch:
            patch.setattr(migrate, "_MIGRATIONS_DIR", old)
            migrate.run_migrations(pool)
        with pool.transaction() as conn:
            conn.execute(
                "INSERT INTO users(username,password_hash,role,created_at) VALUES('owner','x','user',1)"
            )
            conn.execute(
                "INSERT INTO agents(agent_id,user_id,name,created_at,updated_at) VALUES('agent',1,'Private',1,1)"
            )
            conn.execute(
                "INSERT INTO threads(thread_id,agent_id,user_id,channel_type,session_key,created_at,last_active) VALUES('thread','agent',1,'resident','resident-key',1,1)"
            )
            conn.execute(
                "INSERT INTO resident_conversations(owner_id,agent_id,thread_id,status,created_at,updated_at) VALUES(1,'agent','thread','ready',1,1)"
            )
            conn.execute(
                "INSERT INTO resident_requests(request_id,turn_id,owner_id,thread_id,prompt,reply,status,created_at,updated_at) VALUES('accepted','turn',1,'thread','Question','Partial','interrupted',1000,2000)"
            )
            before = dict(conn.execute("SELECT * FROM resident_requests").fetchone())
            conn.execute("UPDATE _schema_version SET version=?", (watermark,))
        migrate.run_migrations(pool)
        migrate.run_migrations(pool)
        with pool.connect() as conn:
            after = dict(conn.execute("SELECT * FROM resident_requests").fetchone())
            assert after.pop("day_key") == after.pop("timezone") == ""
            assert after.pop("input_json") == "{}"
            assert after == before
            assert conn.execute("SELECT version FROM _schema_version").fetchone()[0] == 53
            assert "message_json" in {
                row["name"] for row in conn.execute("PRAGMA table_info(resident_task_reports)")
            }
            assert conn.execute("PRAGMA foreign_key_check").fetchall() == []
    finally:
        pool.close()


def test_resident_closed_loop_dialects_have_equivalent_constraints():
    sqlite = (migrate._MIGRATIONS_DIR / "052_resident_closed_loop.sql").read_text()
    postgres = (migrate._MIGRATIONS_DIR / "052_resident_closed_loop.pg.sql").read_text()
    postgres = postgres.replace(
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT"
    ).replace("owner_id BIGINT", "owner_id INTEGER")
    assert re.sub(r"\s+", " ", sqlite).strip() == re.sub(r"\s+", " ", postgres).strip()
